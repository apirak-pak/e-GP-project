"""Tables used by the dashboard in a dedicated Supabase egp schema."""

from __future__ import annotations

from app.db import connect_postgres


def init_db_postgres() -> None:
    with connect_postgres() as conn:
        conn.execute("CREATE SCHEMA IF NOT EXISTS egp")
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS egp.projects (
                project_id TEXT PRIMARY KEY,
                title TEXT NOT NULL,
                province TEXT NOT NULL,
                project_type TEXT NOT NULL DEFAULT '',
                agency TEXT NOT NULL DEFAULT '',
                status TEXT NOT NULL,
                budget DOUBLE PRECISION,
                reference_price DOUBLE PRECISION,
                winning_price DOUBLE PRECISION,
                winner TEXT NOT NULL DEFAULT '',
                announced_at TEXT NOT NULL DEFAULT '',
                source_url TEXT NOT NULL DEFAULT '',
                is_demo INTEGER NOT NULL DEFAULT 0,
                source_kind TEXT NOT NULL DEFAULT 'manual',
                source_name TEXT NOT NULL DEFAULT '',
                agency_province TEXT NOT NULL DEFAULT '',
                province_source TEXT NOT NULL DEFAULT '',
                updated_at TEXT NOT NULL
            )
            """
        )
        conn.execute("CREATE INDEX IF NOT EXISTS idx_egp_projects_province ON egp.projects(province)")
        conn.execute("CREATE INDEX IF NOT EXISTS idx_egp_projects_agency_province ON egp.projects(agency_province)")
        conn.execute("CREATE INDEX IF NOT EXISTS idx_egp_projects_status ON egp.projects(status)")
        conn.execute("CREATE INDEX IF NOT EXISTS idx_egp_projects_announced ON egp.projects(announced_at DESC, project_id DESC)")
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS egp.import_runs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                source_name TEXT NOT NULL,
                file_sha256 TEXT NOT NULL,
                row_count INTEGER NOT NULL,
                created_count INTEGER NOT NULL,
                updated_count INTEGER NOT NULL,
                imported_at TEXT NOT NULL
            )
            """
        )
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS egp.api_sync_runs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                service TEXT NOT NULL,
                fiscal_year INTEGER NOT NULL,
                keyword TEXT NOT NULL,
                result_total INTEGER NOT NULL,
                fetched_count INTEGER NOT NULL,
                saved_count INTEGER NOT NULL,
                skipped_count INTEGER NOT NULL,
                synced_at TEXT NOT NULL
            )
            """
        )
